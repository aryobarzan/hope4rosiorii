export type CountryCode = (typeof countryCodes)[number];

// Where adopters are most likely to live: listed first, above the full list
const priorityCountryCodes: readonly CountryCode[] = ["LU", "FR", "BE", "DE"];

export type CountryOption = { code: CountryCode; name: string };

/**
 * Country names in the given locale, from the platform's own data
 * (`Intl.DisplayNames`), so there are no translations to maintain.
 * Call it on the server and pass the result down as props: the names then
 * can't differ between server and browser and cause a hydration mismatch.
 */
export function getCountryOptions(locale: string): {
  priority: CountryOption[];
  others: CountryOption[];
} {
  const names = new Intl.DisplayNames(locale, { type: "region" });
  const toOption = (code: CountryCode): CountryOption => ({
    code,
    name: names.of(code) ?? code,
  });

  return {
    priority: priorityCountryCodes.map(toOption),
    others: countryCodes
      .filter((code) => !priorityCountryCodes.includes(code))
      .map(toOption)
      .sort((a, b) => a.name.localeCompare(b.name, locale)),
  };
}
